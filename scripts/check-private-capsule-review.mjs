import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { privateCapsuleFixture } from '../tests/fixtures/private-capsule.mjs';
import { startUiServer } from '../utility/ui/server.mjs';
import { validateRestorePlan } from '../utility/portabase-core.mjs';
import { privateJobReference } from '../src/lib/private-job-reference.js';
import { projectSharedManifest } from '../utility/shared-manifest.mjs';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const fixture = await privateCapsuleFixture();
const targetRef = 'bcdefghijklmnopqrst0';
await writeFile(join(fixture.directory, 'engine.json'), JSON.stringify({ projectRef: fixture.options.projectRef, backupDirectory: 'backups', statusDirectory: 'status' }));
const session = await startUiServer({ privateReview: { ...fixture.options, engineConfigPath: 'engine.json', targetRef }, collect: () => assert.fail('offline review must never contact source') });
const origin = new URL(session.url).origin, evidence = resolve('portabase-evidence/private-capsule-review');
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  for (const width of [320, 1440]) {
    await writeFile(join(fixture.capsule, 'capsule.json'), JSON.stringify(fixture.metadata));
    const page = await browser.newPage({ viewport: { width, height: 1000 } }); const requests = [], errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => { requests.push(route.request().url()); return new URL(route.request().url()).origin === origin ? route.continue() : route.abort(); });
    await page.goto(session.url);
    await page.getByText('Ready to inspect. No source connection needed.', { exact: true }).waitFor();
    assert.equal(new URL(page.url()).hash, '');
    assert.equal(requests.some(url => url.endsWith('/api/review/inspect')), false);
    const inspect = page.getByRole('button', { name: 'Inspect configured capsule', exact: true });
    await inspect.click(); await page.getByText('Capsule inspected privately.', { exact: true }).waitFor();
    assert.match(await page.locator('#log').innerText(), /component.started/);
    assert.doesNotMatch(await page.locator('body').innerText(), /private-row-value|private-raw-diagnostic|private-object.jpg|synthetic-private-customer-passphrase/);
    assert.equal(requests.some(url => url.endsWith('/api/review/shareable-summary')), false);
    await page.getByRole('button', { name: 'Preview shareable summary', exact: true }).click();
    await page.getByText('Summary preview ready. Nothing has been uploaded.', { exact: true }).waitFor();
    const sharedPreview = JSON.parse(await page.getByLabel('Shareable summary preview', { exact: true }).innerText());
    assert.deepEqual(projectSharedManifest(sharedPreview, { projectRef: fixture.options.projectRef }), sharedPreview);
    assert.equal(Object.hasOwn(sharedPreview.counts, 'tableCount'), false);
    assert.doesNotMatch(JSON.stringify(sharedPreview), /orders|images|send-receipt|private-row|private-object|passphrase|captureLog|inventory/);
    const sharingDownloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download shareable summary', exact: true }).click();
    const sharingDownload = await sharingDownloadEvent;
    assert.equal(sharingDownload.suggestedFilename(), 'portabase-shareable-summary.json');
    assert.deepEqual(JSON.parse(await readFile(await sharingDownload.path(), 'utf8')), sharedPreview);
    assert.equal(requests.some(url => new URL(url).pathname.includes('manifest-sharing')), false);
    await page.getByRole('checkbox', { name: 'Select table public.empty', exact: true }).uncheck();
    await page.getByRole('checkbox', { name: 'Select bucket images', exact: true }).uncheck();
    await page.getByRole('checkbox', { name: 'Select function send-receipt', exact: true }).uncheck();
    const save = page.getByRole('button', { name: 'Save private restore plan', exact: true });
    await page.getByLabel('Selected data budget in bytes', { exact: true }).fill('1'); assert.equal(await save.isDisabled(), true);
    await page.getByLabel('Selected data budget in bytes', { exact: true }).fill('100000');
    const posted = page.waitForResponse(response => response.url().endsWith('/api/review/plans'), { timeout: 10000 });
    const [reply] = await Promise.all([posted, save.click({ timeout: 3000 })]).catch(async failure => { console.error({ errors, alert: await page.locator('#error').textContent(), paths: requests.map(url => new URL(url).pathname) }); throw failure; }); assert.equal(reply.status(), 201);
    const saved = await reply.json(), plan = JSON.parse(await readFile(join(fixture.directory, saved.planPath)));
    assert.equal(plan.tables.find(row => row.table === 'orders').selected, true);
    assert.equal(plan.tables.find(row => row.table === 'empty').selected, false);
    assert.equal(plan.buckets[0].selected, false); assert.equal(plan.functions[0].selected, false);
    validateRestorePlan(plan, { capsuleId: fixture.metadata.id });
    await page.getByRole('heading', { name: 'Private restore plan saved', exact: true }).waitFor();
    assert.match(await page.locator('#summary').innerText(), new RegExp(`${saved.selectedBytes.toLocaleString()} B selected`));
    await page.screenshot({ path: join(evidence, `saved-${width}.png`), fullPage: true });
    assert.equal(await save.isDisabled(), true);
    assert.equal(requests.some(url => url.endsWith('/api/review/replay-reference')), false);
    const createReplay = page.getByRole('button', { name: 'Create replay job reference', exact: true });
    assert.equal(await createReplay.isDisabled(), true);
    await page.getByLabel('Retype the recovery target reference', { exact: true }).fill(fixture.options.projectRef);
    await page.getByRole('checkbox', { name: 'I want to prepare a replay job for this saved selection and target', exact: true }).check();
    assert.equal(await createReplay.isDisabled(), true);
    await page.getByLabel('Retype the recovery target reference', { exact: true }).fill(targetRef);
    assert.equal(await createReplay.isDisabled(), false);
    const referenceReply = page.waitForResponse(response => response.url().endsWith('/api/review/replay-reference'));
    const [referenceResponse] = await Promise.all([referenceReply, createReplay.click()]);
    assert.equal(referenceResponse.status(), 201);
    const reference = await referenceResponse.json();
    assert.deepEqual(privateJobReference(reference, { id: fixture.options.runnerId }), reference);
    await page.getByText('Replay reference prepared. No job has been queued.', { exact: true }).waitFor();
    assert.equal(await createReplay.isDisabled(), true);
    const downloaded = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download replay job reference', exact: true }).click();
    const download = await downloaded;
    assert.equal(download.suggestedFilename(), 'portabase-replay-reference.json');
    const file = await readFile(await download.path(), 'utf8');
    assert.deepEqual(JSON.parse(file), reference);
    assert.equal(Object.keys(JSON.parse(file)).length, 5);
    assert.doesNotMatch(file, /targetRef|projectRef|planRef|bindingSha256|public|orders|passphrase|engine/);
    assert.deepEqual(await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } })), { local: {}, session: {} });
    assert.equal(requests.some(url => new URL(url).pathname === '/api/cloud/jobs'), false);
    await page.screenshot({ path: join(evidence, `replay-reference-${width}.png`), fullPage: true });
    await inspect.click(); await page.getByText('Capsule inspected privately.', { exact: true }).waitFor();
    assert.equal(await page.locator('#sharing-preview').isHidden(), true);
    assert.equal(await page.locator('#download-sharing').isDisabled(), true);
    for (const name of ['Select table public.orders', 'Select table public.empty', 'Select bucket images', 'Select function send-receipt']) await page.getByRole('checkbox', { name, exact: true }).uncheck();
    assert.equal(await save.isDisabled(), true);
    await page.getByRole('checkbox', { name: 'I intend to save with no data or functions selected', exact: true }).check();
    assert.equal(await save.isDisabled(), false);
    await writeFile(join(fixture.capsule, 'capsule.json'), JSON.stringify({ ...fixture.metadata, status: 'PARTIAL' }));
    await inspect.click(); await page.getByRole('alert').waitFor(); assert.equal(await page.locator('#save').isDisabled(), true); assert.equal(await page.locator('#review').isHidden(), true);
    assert.equal(await page.locator('#preview-sharing').isDisabled(), true);
    assert.equal(await page.locator('#download-sharing').isDisabled(), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.equal(await page.locator('input[type="password"]').count(), 0);
    assert.equal(requests.every(url => new URL(url).origin === origin), true); assert.deepEqual(errors, []);
    await page.close();
  }
  console.log('Private capsule review: actual encrypted fixture, 320/1440px, explicit sharing preview/download validated by dashboard schema, capture log, selection/budget gates, separate save and target-confirmed opaque replay download, no autoqueue/upload, stale sharing preview cleared, failed refresh, no browser storage/external requests/overflow.');
} finally { await browser.close(); await session.close(); }
